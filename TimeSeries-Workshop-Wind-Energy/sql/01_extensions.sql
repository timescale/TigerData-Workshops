-- ============================================================================
-- # Wind Energy — Step 01: Extensions and Configuration
-- ============================================================================
-- This part of the workshop models a globally distributed fleet of wind
-- turbines at FIXED coordinates. Each turbine reports wind speed and
-- direction; power output is then DERIVED from wind speed using the standard
-- turbine power equation rather than stored as a fake measurement.
--
-- That distinction is the teaching point. Raw sensor data is cheap to collect
-- and expensive to interpret. The value sits in the derived metric — and a
-- derived metric computed by an IMMUTABLE SQL function is reproducible,
-- testable, and usable inside continuous aggregates.
-- ============================================================================
-- ## Prerequisites
-- ============================================================================
-- 1. A TigerData Cloud service
--    https://console.cloud.timescale.com/signup
--
-- 2. Connection string from the TigerData Console:
--    postgres://tsdbadmin:<password>@<host>:<port>/tsdb?sslmode=require
--
-- 3. psql CLI installed (recommended):
--    https://www.tigerdata.com/blog/how-to-install-psql-on-mac-ubuntu-debian-windows
--
-- 4. Basic SQL knowledge
-- ============================================================================
-- ## What You'll Learn
-- ============================================================================
-- - PostGIS geography:     storing turbine locations for true metre-accurate distance
-- - Spatial indexing:      GiST indexes and why ST_DWithin beats ST_Distance
-- - Point-in-polygon:      assigning each turbine to a named region at seed time
-- - Derived metrics:       an IMMUTABLE power curve, not a lookup table
-- - Hypertables:           time-partitioned storage for the measurement stream
-- - Continuous aggregates: hourly, daily, and per-region rollups that self-refresh
-- - Columnstore + retention: automated data lifecycle for raw telemetry
-- ============================================================================


